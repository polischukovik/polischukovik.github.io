import {
  DEFAULT_RETENTION_DAYS,
  clearAllRuns,
  deleteRun,
  ensureRetentionPolicy,
  getRun,
  listRuns,
  saveRun,
} from './local-run-store.js';

const runForm = document.getElementById('run-form');
const pipelineNameSelect = document.getElementById('pipeline-name');
const runStatusSelect = document.getElementById('run-status');
const runIntervalInput = document.getElementById('run-interval');
const retentionDaysInput = document.getElementById('retention-days');
const reportContentInput = document.getElementById('report-content-input');
const cleanupButton = document.getElementById('cleanup-button');
const clearButton = document.getElementById('clear-button');
const refreshButton = document.getElementById('refresh-button');
const pageStatus = document.getElementById('page-status');
const runsBody = document.getElementById('runs-body');
const selectedMeta = document.getElementById('selected-meta');
const selectedReport = document.getElementById('selected-report');
const diagnostics = document.getElementById('diagnostics');

function setStatus(message, type = '') {
  pageStatus.textContent = message;
  pageStatus.className = `status ${type}`.trim();
}

function formatTime(value) {
  if (!value) return '-';
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime()) ? value : parsed.toLocaleString();
}

function getRetentionDays() {
  const parsed = Number(retentionDaysInput.value);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : DEFAULT_RETENTION_DAYS;
}

function renderRunsTable(runs) {
  runsBody.innerHTML = '';

  if (!runs.length) {
    const tr = document.createElement('tr');
    tr.innerHTML = '<td colspan="6">No local runs saved.</td>';
    runsBody.appendChild(tr);
    return;
  }

  runs.forEach((run) => {
    const tr = document.createElement('tr');
    tr.innerHTML = `
      <td>${run.id}</td>
      <td>${run.pipelineName}</td>
      <td><span class="status-pill status-${String(run.status).toLowerCase()}">${run.status}</span></td>
      <td>${run.humanReadableInterval || run.providedInterval || '-'}</td>
      <td>${formatTime(run.startedAt)}</td>
      <td>
        <button type="button" class="action-btn" data-action="view" data-run-id="${run.id}">View</button>
        <button type="button" class="action-btn secondary" data-action="delete" data-run-id="${run.id}">Delete</button>
      </td>
    `;
    runsBody.appendChild(tr);
  });
}

async function refreshRunsTable() {
  const runs = await listRuns({ limit: 30 });
  renderRunsTable(runs);
  return runs;
}

async function viewRun(runId) {
  const run = await getRun(runId);
  if (!run) {
    selectedMeta.textContent = '';
    selectedReport.textContent = 'Run not found.';
    return;
  }

  selectedMeta.textContent = `${run.pipelineName} • ${run.status} • ${formatTime(run.startedAt)}`;
  selectedReport.textContent = JSON.stringify(run, null, 2);
}

function buildMockRun() {
  const now = new Date();
  const pipelineName = pipelineNameSelect.value;
  const interval = runIntervalInput.value.trim() || 'custom';

  return {
    pipelineName,
    status: runStatusSelect.value,
    providedInterval: interval,
    humanReadableInterval: interval,
    startedAt: now.toISOString(),
    durationMs: Math.floor(Math.random() * 5000),
    reportFilename: `${pipelineName}_${now.toISOString().replace(/[:.]/g, '_')}.txt`,
    reportContent: reportContentInput.value,
    summary: {
      generatedAt: now.toISOString(),
      note: 'Mock run generated by local storage POC',
    },
    metadata: {
      source: 'local-runs-poc',
    },
  };
}

async function saveMockRun() {
  const saved = await saveRun(buildMockRun());
  const cleanupResult = await ensureRetentionPolicy({ retentionDays: getRetentionDays() });
  await refreshRunsTable();
  await viewRun(saved.id);
  diagnostics.textContent = JSON.stringify({
    action: 'save',
    savedRunId: saved.id,
    cleanupResult,
  }, null, 2);
  setStatus(`Saved local run ${saved.id}.`, 'ok');
}

async function runCleanup() {
  const result = await ensureRetentionPolicy({
    retentionDays: getRetentionDays(),
    minIntervalHours: 0,
  });
  await refreshRunsTable();
  diagnostics.textContent = JSON.stringify({
    action: 'cleanup',
    result,
  }, null, 2);
  setStatus('TTL cleanup completed.', 'ok');
}

async function clearRuns() {
  await clearAllRuns();
  await refreshRunsTable();
  selectedMeta.textContent = '';
  selectedReport.textContent = 'Local run cache cleared.';
  diagnostics.textContent = JSON.stringify({
    action: 'clearAll',
    clearedAt: new Date().toISOString(),
  }, null, 2);
  setStatus('All local runs cleared.', 'ok');
}

runForm.addEventListener('submit', async (event) => {
  event.preventDefault();

  try {
    await saveMockRun();
  } catch (error) {
    setStatus(error.message, 'error');
  }
});

cleanupButton.addEventListener('click', async () => {
  try {
    await runCleanup();
  } catch (error) {
    setStatus(error.message, 'error');
  }
});

clearButton.addEventListener('click', async () => {
  try {
    await clearRuns();
  } catch (error) {
    setStatus(error.message, 'error');
  }
});

refreshButton.addEventListener('click', async () => {
  try {
    await refreshRunsTable();
    setStatus('Local runs refreshed.', 'ok');
  } catch (error) {
    setStatus(error.message, 'error');
  }
});

runsBody.addEventListener('click', async (event) => {
  const target = event.target;
  if (!(target instanceof HTMLButtonElement)) return;

  const action = target.dataset.action;
  const runId = target.dataset.runId;
  if (!action || !runId) return;

  try {
    if (action === 'view') {
      await viewRun(runId);
      setStatus(`Loaded run ${runId}.`, 'ok');
      return;
    }

    if (action === 'delete') {
      await deleteRun(runId);
      await refreshRunsTable();
      if (selectedMeta.textContent.includes(runId)) {
        selectedMeta.textContent = '';
        selectedReport.textContent = 'Selected run was deleted.';
      }
      diagnostics.textContent = JSON.stringify({
        action: 'delete',
        deletedRunId: runId,
      }, null, 2);
      setStatus(`Deleted run ${runId}.`, 'ok');
    }
  } catch (error) {
    setStatus(error.message, 'error');
  }
});

async function boot() {
  retentionDaysInput.value = String(DEFAULT_RETENTION_DAYS);
  await ensureRetentionPolicy({ retentionDays: getRetentionDays() });
  await refreshRunsTable();
  setStatus('Local run store ready.', 'ok');
}

boot().catch((error) => {
  setStatus(error.message, 'error');
  diagnostics.textContent = JSON.stringify({
    action: 'boot',
    error: String(error),
  }, null, 2);
});
